-- T-01 USERS
CREATE TABLE USERS (
    USER_ID              NUMBER GENERATED BY DEFAULT AS IDENTITY,
    EMAIL                VARCHAR2(255) NOT NULL,
    PASSWORD_HASH        VARCHAR2(255) NOT NULL,
    NAME                 VARCHAR2(100) NOT NULL,
    ROLE                 VARCHAR2(20) NOT NULL,
    CREATED_AT           TIMESTAMP NOT NULL,
    UPDATED_AT           TIMESTAMP NOT NULL,
    DELETED_AT           TIMESTAMP,
    CONSTRAINT PK_USERS PRIMARY KEY (USER_ID),
    CONSTRAINT UK_USERS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USERS_ROLE CHECK (ROLE IN ('CUSTOMER', 'PLANNER', 'ADMIN'))
);

COMMENT ON TABLE USERS IS '利用者の情報（氏名・メールアドレス・パスワード・種別など）';
COMMENT ON COLUMN USERS.USER_ID IS '利用者を識別する番号（主キー）';
COMMENT ON COLUMN USERS.EMAIL IS 'メールアドレス（ログインID）';
COMMENT ON COLUMN USERS.PASSWORD_HASH IS 'BCryptでハッシュ化したパスワード';
COMMENT ON COLUMN USERS.NAME IS '氏名';
COMMENT ON COLUMN USERS.ROLE IS '利用者種別（CUSTOMER / PLANNER / ADMIN）';
COMMENT ON COLUMN USERS.CREATED_AT IS '登録日時';
COMMENT ON COLUMN USERS.UPDATED_AT IS '最終更新日時';
COMMENT ON COLUMN USERS.DELETED_AT IS '削除日時（NULL = 有効、日時あり = 論理削除済）';

